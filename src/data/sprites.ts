const mapSpriteRarities = (rawList: Sprite[]): Sprite[] => {
  return rawList.map((s) => {
    const isSpecial =
      ['Gold', 'CheatMaster', 'Galaxy', 'Gummy', 'Holofoil', 'Gem', 'Cube'].includes(s.variant) ||
      ['Gold', 'CheatMaster', 'Galaxy', 'Gummy', 'Holofoil', 'Gem', 'Cube'].includes(s.category);
    return {
      ...s,
      rarity: isSpecial ? 'Special' : NAME_TO_RARITY[s.name] || s.rarity,
    };
  });
};

